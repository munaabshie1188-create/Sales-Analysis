--5.Find the 10 products that have been returned the most. How much money was generated by these products?--
WITH sales AS (
    SELECT 
        s.ProductKey, 
        SUM(s.OrderQuantity) AS sold_qty,
        SUM(s.OrderQuantity * p.ProductPrice) AS sales_revenue
    FROM adv_sales_all s
    JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
    GROUP BY s.ProductKey
),
returns AS (
    SELECT 
        r.ProductKey, 
        SUM(r.ReturnQuantity) AS returned_qty
    FROM adv_return r
    GROUP BY r.ProductKey
)
SELECT 
    p.ProductKey, 
    p.ProductName,
    COALESCE(s.sold_qty, 0) AS sold_qty,
    COALESCE(r.returned_qty, 0) AS returned_qty,
    COALESCE(s.sales_revenue, 0) - COALESCE(r.returned_qty, 0) * p.ProductPrice AS net_revenue
FROM adv_prod_lookup p
LEFT JOIN sales s ON p.ProductKey = s.ProductKey
LEFT JOIN returns r ON p.ProductKey = r.ProductKey
ORDER BY COALESCE(r.returned_qty, 0) DESC
LIMIT 10;



--6.Get a list of customers who have placed orders in more than one territory.--
SELECT cu.CustomerKey, cu.FirstName, cu.LastName,
       COUNT(DISTINCT s.TerritoryKey) AS territory_count
FROM adv_sales_all s
JOIN advcustomer cu ON s.CustomerKey = cu.CustomerKey
GROUP BY cu.CustomerKey, cu.FirstName, cu.LastName
HAVING COUNT(DISTINCT s.TerritoryKey) > 1
ORDER BY territory_count DESC;

--7.Retrieve the product names and their corresponding sub-categories for products that have been ordered at least 10 times.--
SELECT p.ProductKey, p.ProductName, sc.SubcategoryName,
       SUM(s.OrderQuantity) AS total_ordered_qty
FROM adv_sales_all s
JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
JOIN adv_prod_sub_cat sc ON p.ProductSubcategoryKey = sc.ProductSubcategoryKey
GROUP BY p.ProductKey, p.ProductName, sc.SubcategoryName
HAVING SUM(s.OrderQuantity) >= 10
ORDER BY total_ordered_qty DESC;

--8.List the customer names who have placed orders after 2021. What is the distribution of their occupation?--
