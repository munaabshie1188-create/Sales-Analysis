--1) Retrieve the customers who have placed orders with a total amount greater than $10000--
SELECT fullname, s.customerkey, 
SUM(s.orderquantity * p.productprice) totalrevenue
FROM advcustomer c
JOIN 
(SELECT *
FROM advsales2020
UNION ALL 
SELECT *
FROM advsales2021
UNION ALL
SELECT *
FROM advsales2022) AS s ON c.customerkey = s.customerkey
JOIN adv_prod_lookup p ON s.productkey = p.productkey
GROUP BY s.customerkey, fullname
HAVING SUM(s.orderquantity * p.productprice) > 10000
LIMIT 5;


--2) Retrieve the total revenue and total orders generated by each product category--
SELECT c.CategoryName,
       SUM(s.OrderQuantity * p.ProductPrice) AS total_revenue,
       COUNT(*) AS total_order_rows,
       COUNT(DISTINCT s.OrderNumber) AS distinct_order_count
FROM adv_sales_all s
JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
JOIN adv_prod_sub_cat sc ON p.ProductSubcategoryKey = sc.ProductSubcategoryKey
JOIN adv_prod_cat c ON sc.ProductCategoryKey = c.ProductCategoryKey
GROUP BY c.CategoryName
ORDER BY total_revenue DESC;



--3.Retrieve the names of products and their categories for products with a selling price greater than the average selling price of all products.--
WITH avg_price AS (
  SELECT AVG(ProductPrice) AS avg_price FROM adv_prod_lookup
)
SELECT p.ProductKey, p.ProductName, p.ProductPrice, c.CategoryName
FROM adv_prod_lookup p
JOIN adv_prod_sub_cat sc ON p.ProductSubcategoryKey = sc.ProductSubcategoryKey
JOIN adv_prod_cat c ON sc.ProductCategoryKey = c.ProductCategoryKey
CROSS JOIN avg_price
WHERE p.ProductPrice > avg_price.avg_price
ORDER BY p.ProductPrice DESC;

