--9.Get a list of products and their corresponding order quantities for products that have been ordered at least once.--
SELECT p.ProductKey, p.ProductName, SUM(s.OrderQuantity) AS total_ordered_qty
FROM adv_sales_all s
JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
GROUP BY p.ProductKey, p.ProductName
HAVING SUM(s.OrderQuantity) > 0
ORDER BY total_ordered_qty DESC;

--10.Retrieve the product names that start with the letter "C" or “H” and are from the "Clothing" category.--
SELECT p.ProductKey, p.ProductName, c.CategoryName
FROM adv_prod_lookup p
JOIN adv_prod_sub_cat sc ON p.ProductSubcategoryKey = sc.ProductSubcategoryKey
JOIN adv_prod_cat c ON sc.ProductCategoryKey = c.ProductCategoryKey
WHERE c.CategoryName = 'Clothing'
  AND (p.ProductName ILIKE 'C%' OR p.ProductName ILIKE 'H%')
ORDER BY p.ProductName;

--11.Retrieve the product names that have been ordered in the ‘United States’ or "Australia".--
SELECT DISTINCT p.ProductKey, p.ProductName, l.Country
FROM adv_sales_all s
JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
JOIN adv_location l ON s.TerritoryKey = l.SalesTerritoryKey
WHERE l.Country IN ('United States', 'Australia')
ORDER BY p.ProductName;

--12.Find the customer names who have placed orders with a total amount greater than the average total amount of orders.--
WITH cust_totals AS (
  SELECT s.CustomerKey, SUM(s.OrderQuantity * p.ProductPrice) AS total_amount
  FROM adv_sales_all s
  JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
  GROUP BY s.CustomerKey
),
avg_total AS (
  SELECT AVG(total_amount) AS avg_amount FROM cust_totals
)
SELECT ct.CustomerKey, cu.FirstName, cu.LastName, ct.total_amount
FROM cust_totals ct
JOIN avg_total a ON 1=1
JOIN advcustomer cu ON cu.CustomerKey = ct.CustomerKey
WHERE ct.total_amount > a.avg_amount
ORDER BY ct.total_amount DESC;

--13.Retrieve the top 5 customers who have placed the highest number of orders, along with their order counts.--
SELECT cu.CustomerKey, cu.FirstName, cu.LastName,
       COUNT(DISTINCT s.OrderNumber) AS order_count
FROM adv_sales_all s
JOIN advcustomer cu ON s.CustomerKey = cu.CustomerKey
GROUP BY cu.CustomerKey, cu.FirstName, cu.LastName
ORDER BY order_count DESC
LIMIT 5;

--14.List the customers who have placed orders within the last 6 months (consider the last date in the data)--
WITH max_date AS (
  SELECT MAX(OrderDate) AS max_order_date FROM adv_sales_all
)
SELECT DISTINCT cu.CustomerKey, cu.FirstName, cu.LastName, s.OrderDate
FROM adv_sales_all s
JOIN advcustomer cu ON s.CustomerKey = cu.CustomerKey
CROSS JOIN max_date
WHERE s.OrderDate BETWEEN (max_date.max_order_date - INTERVAL '6 months') AND max_date.max_order_date
ORDER BY s.OrderDate DESC;

--15.We want to reach out to our best customers in 2022. Can you get emails of Top 50 customers based on revenue?--
SELECT cu.CustomerKey, cu.FirstName, cu.LastName, cu.EmailAddress,
       SUM(s.OrderQuantity * p.ProductPrice) AS revenue_2022
FROM adv_sales_all s
JOIN adv_prod_lookup p ON s.ProductKey = p.ProductKey
JOIN advcustomer cu ON s.CustomerKey = cu.CustomerKey
WHERE EXTRACT(YEAR FROM s.OrderDate) = 2022
GROUP BY cu.CustomerKey, cu.FirstName, cu.LastName, cu.EmailAddress
ORDER BY revenue_2022 DESC
LIMIT 50;



